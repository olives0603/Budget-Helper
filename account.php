    document.getElementById("account-label").textContent = account.email;
    showMembershipAd(account.membership);
    if (typeof renderMembership === "function") renderMembership(account.membership);
  }).catch(showError);
});
sessionReady.catch((error) => {
  document.getElementById("page-status").textContent =
    "Refresh this page after the server is available.";
  showError(error);
});
document.getElementById("logout").addEventListener("click", async (event) => {
  event.currentTarget.disabled = true;
  try {
    const token = await api("/api/csrf");
    // Submit a normal form so Python can send the user back to login.
    const form = document.createElement("form");
    form.method = "POST";
    form.action = API_ORIGIN + "/api/logout";
    const input = document.createElement("input");
    input.type = "hidden";
    input.name = "csrf_token";
    input.value = token.csrf_token;
    form.append(input);
    document.body.append(form);
    form.submit();
  } catch (error) {
    showError(error);
    event.currentTarget.disabled = false;
  }
});


// Account form | Keep errors beside the form and keep typed values after a failed save.
const accountForm = document.getElementById("account-form");
function accountNotice(id, text) {
  const node = document.getElementById(id);
  node.textContent = text;
  node.hidden = !text;
}
accountForm.addEventListener("submit", async event => {
  event.preventDefault();
  accountNotice("account-error", "");
  accountNotice("account-message", "");
  const data = new FormData(accountForm);
  if (data.get("new_password") !== data.get("confirm_password")) {
    accountNotice("account-error", "The new passwords do not match.");
    return;
  }
  document.getElementById("account-fields").disabled = true;
  try {
    const result = await post("/api/account/update", data);
    document.getElementById("account-label").textContent = result.email;
    accountForm.elements.email.value = result.email;
    for (const name of ["current_password", "new_password", "confirm_password"]) {
      accountForm.elements[name].value = "";
    }
    accountNotice("account-message", result.message);
  } catch(error) { accountNotice("account-error", error.message); }
  finally { document.getElementById("account-fields").disabled = false; }
});

// Membership display | Python decides access. These buttons only reflect its answer.
function renderMembership(membership) {
  document.getElementById("membership-status").textContent = membership.is_premium
    ? "Demo Premium active. " + (membership.cancel_at_period_end ? "Access ends on " : "Next demo renewal: ") + membership.expires_on + "."
    : "Free account. Demo advertisements are shown.";
  const toggle = document.getElementById("premium-toggle");
  toggle.textContent = membership.is_premium ? "Disable demo Premium" : "Enable demo Premium";
  toggle.setAttribute("aria-pressed", String(membership.is_premium));
  toggle.dataset.action = membership.is_premium ? "disable" : "enable";
  const subscribe = document.getElementById("premium-subscribe");
  subscribe.hidden = membership.is_premium && !membership.cancel_at_period_end;
  subscribe.textContent = membership.is_premium ? "Resume demo renewal" : "Start demo Premium";
  document.getElementById("premium-cancel").hidden = !membership.is_premium || membership.cancel_at_period_end;
  document.getElementById("premium-export").hidden = !membership.is_premium;
  showMembershipAd(membership);
}
async function changeMembership(action) {
  accountNotice("membership-error", "");
  const buttons = ["premium-subscribe", "premium-cancel", "premium-toggle"];
  buttons.forEach(id => document.getElementById(id).disabled = true);
  try {
    const result = await post("/api/account/premium/" + action, new FormData());
    renderMembership(result.membership);
    // Other open pages listen for this and ask Python for the saved membership.
    try { localStorage.setItem("budgetbuddy-membership-change", String(Date.now())); } catch (_) {}
  } catch(error) { accountNotice("membership-error", error.message); }
  finally { buttons.forEach(id => document.getElementById(id).disabled = false); }
}
document.getElementById("premium-toggle").onclick = event => changeMembership(event.currentTarget.dataset.action);
document.getElementById("premium-subscribe").onclick = () => changeMembership("subscribe");
document.getElementById("premium-cancel").onclick = () => changeMembership("cancel");

// CSV download | Ask the server again so an expired membership cannot bypass the check.
document.getElementById("premium-export").onclick = async event => {
  const button = event.currentTarget;
  button.disabled = true;
  accountNotice("membership-error", "");
  try {
    const response = await fetch(API_ORIGIN + "/api/account/export", {credentials:"include", cache:"no-store"});
    if (!response.ok) {
      const result = await response.json();
      throw new Error(result.message || "The download could not be completed.");
    }
    const url = URL.createObjectURL(await response.blob());
    const link = document.createElement("a");
    link.href = url;
    link.download = "budgetbuddy-finances.csv";
    document.body.append(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  } catch(error) { accountNotice("membership-error", error.message); }
  finally { button.disabled = false; }
};
